"""Deterministic Reward & Verifier Synthesis Engine for MYAI.

Infers deterministic verifiers (numeric, json_schema, regex, tool_call) from reference
dataset samples, validates against negative controls, and synthesizes standalone, committable
Python reward scripts (reward.py) with calibration reports.
"""
from __future__ import annotations

import json
import re
import math
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple


@dataclass
class CalibrationReport:
    family: str                     # "numeric", "json_schema", "regex", "tool_call"
    samples_analyzed: int
    reference_pass_rate: float      # Must be 1.0 (100% on valid references)
    negative_rejection_rate: float  # >= 0.95 (rejects corrupted answers)
    parameters: Dict[str, Any]
    verdict: str                    # "CALIBRATED" | "UNRELIABLE"


@dataclass
class VerifierCandidate:
    family: str
    confidence: float
    parameters: Dict[str, Any]
    python_code: str


def _try_parse_numeric(text: str) -> Optional[float]:
    match = re.search(r"[-+]?\d+(?:\.\d+)?", text)
    if match:
        try:
            return float(match.group(0))
        except ValueError:
            return None
    return None


def _try_parse_json(text: str) -> Optional[Dict[str, Any]]:
    clean = text.strip()
    if clean.startswith("```json"):
        clean = clean[7:]
    if clean.endswith("```"):
        clean = clean[:-3]
    clean = clean.strip()
    try:
        data = json.loads(clean)
        if isinstance(data, dict):
            return data
    except Exception:
        pass
    return None


def _try_parse_tool_call(text: str) -> Optional[Dict[str, Any]]:
    data = _try_parse_json(text)
    if data and ("name" in data or "function" in data or "tool" in data):
        return data
    return None


