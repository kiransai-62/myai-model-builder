def _evaluate_candidate_directly(candidate: VerifierCandidate, text: str) -> Dict[str, Any]:
    # Safe deterministic evaluator without dynamic execution
    fam = candidate.family
    params = candidate.parameters

    if fam == "tool_call":
        data = _try_parse_tool_call(text)
        if not data:
            return {"valid": False, "score": 0.0}
        name_key = params.get("name_key", "name")
        expected_names = params.get("expected_names", [])
        name = data.get(name_key)
        if not name or (expected_names and name not in expected_names):
            return {"valid": False, "score": 0.0}
        if "arguments" in data and not isinstance(data["arguments"], dict):
            return {"valid": False, "score": 0.0}
        return {"valid": True, "score": 1.0}

    elif fam == "json_schema":
        data = _try_parse_json(text)
        if not data:
            return {"valid": False, "score": 0.0}
        required_keys = params.get("required_keys", [])
        key_types = params.get("key_types", {})
        for k in required_keys:
            if k not in data:
                return {"valid": False, "score": 0.0}
            exp_t = key_types.get(k)
            if exp_t and exp_t != "any" and type(data[k]).__name__ != exp_t:
                return {"valid": False, "score": 0.0}
        return {"valid": True, "score": 1.0}

    elif fam == "numeric":
        val = _try_parse_numeric(text)
        if val is None:
            return {"valid": False, "score": 0.0}
        min_v = params.get("min_val", -float("inf"))
        max_v = params.get("max_val", float("inf"))
        if min_v <= val <= max_v:
            return {"valid": True, "score": 1.0}
        return {"valid": False, "score": 0.0}

    elif fam == "regex":
        pattern = params.get("pattern", "^")
        if re.search(pattern, text.strip(), re.MULTILINE):
            return {"valid": True, "score": 1.0}
        return {"valid": False, "score": 0.0}

    return {"valid": False, "score": 0.0}


def calibrate_verifier(candidate: VerifierCandidate, references: List[str]) -> CalibrationReport:
    """Executes the candidate verifier against references and synthesized negative controls safely."""
    ref_passes = 0
    for r in references:
        res = _evaluate_candidate_directly(candidate, r)
        if res.get("valid", False) and res.get("score", 0.0) >= 0.99:
            ref_passes += 1
    ref_pass_rate = ref_passes / max(1, len(references))

    # Generate and Test Negative Controls
    negative_controls = [
        "I cannot help with that.",
        "Error: undefined symbol null",
        "404 Not Found",
        "{invalid json: missing_quotes}",
        "9999999999.9999",
        "```yaml\nfoo: bar\n```",
    ]
    neg_rejections = 0
    for n in negative_controls:
        res = _evaluate_candidate_directly(candidate, n)
        if not res.get("valid", True) or res.get("score", 1.0) == 0.0:
            neg_rejections += 1
    neg_rejection_rate = neg_rejections / len(negative_controls)

    verdict = "CALIBRATED" if ref_pass_rate >= 0.99 and neg_rejection_rate >= 0.80 else "UNRELIABLE"

    return CalibrationReport(
        family=candidate.family,
        samples_analyzed=len(references),
        reference_pass_rate=round(ref_pass_rate, 4),
        negative_rejection_rate=round(neg_rejection_rate, 4),
        parameters=candidate.parameters,
        verdict=verdict,
    )


def synthesize_reward_script(
    references_file: Path,
    output_py: Path,
    report_json: Optional[Path] = None,
) -> Tuple[Path, CalibrationReport]:
    """Reads reference samples from JSONL/JSON, infers verifier, calibrates, and writes reward.py."""
    refs: List[str] = []
    text = references_file.read_text(encoding="utf-8")
    if references_file.suffix.lower() == ".jsonl":
        for line in text.strip().splitlines():
            if not line.strip():
                continue
            data = json.loads(line)
            r = data.get("response") or data.get("output") or data.get("chosen") or data.get("text")
            if r:
                refs.append(str(r))
    else:
        try:
            data = json.loads(text)
            if isinstance(data, list):
                for item in data:
                    r = item.get("response") or item.get("output") if isinstance(item, dict) else str(item)
                    if r:
                        refs.append(str(r))
        except Exception:
            refs = [l for l in text.splitlines() if l.strip()]

    if not refs:
        raise ValueError(f"No reference outputs could be extracted from {references_file}")

    candidate = infer_verifier(refs)
    calib = calibrate_verifier(candidate, refs)

    output_py.parent.mkdir(parents=True, exist_ok=True)
    output_py.write_text(candidate.python_code, encoding="utf-8")

    if report_json:
        report_json.parent.mkdir(parents=True, exist_ok=True)
        report_data = {
            "family": calib.family,
            "verdict": calib.verdict,
            "samples_analyzed": calib.samples_analyzed,
            "reference_pass_rate": calib.reference_pass_rate,
            "negative_rejection_rate": calib.negative_rejection_rate,
            "parameters": calib.parameters,
            "synthesized_file": str(output_py),
        }
        report_json.write_text(json.dumps(report_data, indent=2), encoding="utf-8")

    return output_py, calib
